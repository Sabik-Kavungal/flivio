interface ColourSpec {
  colour: string;
  colourHex: string;
  image: string;
  stocks: Record<'XS' | 'S' | 'M' | 'L' | 'XL', number>;
}

function buildTopVariants(
  productId: string,
  skuPrefix: string,
  sellingPrice: number,
  originalPrice: number,
  colours: ColourSpec[]
): ProductVariant[] {
  const sizes: ('XS' | 'S' | 'M' | 'L' | 'XL')[] = ['XS', 'S', 'M', 'L', 'XL'];
  const all: ProductVariant[] = [];

  colours.forEach((col) => {
    const code = col.colour
      .replace(/[^a-zA-Z]/g, '')
      .slice(0, 3)
      .toUpperCase();
    sizes.forEach((size) => {
      all.push({
        id: `var_${productId}_${code.toLowerCase()}_${size.toLowerCase()}`,
        productId,
        variantName: `${col.colour} / ${size}`,
        size,
        colour: col.colour,
        colourHex: col.colourHex,
        sku: `${skuPrefix}-${code}-${size}`,
        sellingPrice,
        originalPrice,
        stock: col.stocks[size],
        images: [col.image],
        isActive: true,
      });
    });
  });

  return all;
}

